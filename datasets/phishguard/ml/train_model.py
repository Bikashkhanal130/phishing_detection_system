"""
train_model.py
==============
End-to-end training pipeline for the PhishGuard phishing-URL classifier.

Implements the 11 required steps:
    1.  Load dataset, check shape / missing values / class distribution
    2.  Remove duplicates, fill numeric nulls with median
    3.  Extract the 15 features from the URL column
    4.  StandardScaler: fit_transform on train, transform on test
    5.  Train 6 models (LogReg, DecisionTree, RandomForest, XGBoost, GaussianNB, SVC)
    6.  Evaluate each (accuracy / precision / recall / F1 / confusion matrix) -> table
    7.  GridSearchCV on the best model (cv=5, scoring='f1')
    8.  Final evaluation on the test set -> classification_report
    9.  Save models/optimized_model.pkl, models/scaler.pkl, models/feature_names.json
    10. Convert to ONNX with skl2onnx -> models/phishing_model.onnx
    11. Verify ONNX with onnxruntime on 5 test samples (predictions match sklearn)

Target: F1 >= 0.85 on the 20% test set.

Dataset selection (auto):
    Prefers the real PhiUSIIL dataset if present, otherwise the local
    archive CSV, otherwise the synthetic data/phishing_urls.csv generated by
    build_dataset.py. All paths are resolved relative to this file.
"""

import os
import json
import glob
import sys
import warnings

# Force UTF-8 stdout so emoji / box-drawing chars never crash on Windows cp1252.
try:
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
except Exception:
    pass

import numpy as np
import pandas as pd

from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.svm import SVC
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report,
)

import joblib
from xgboost import XGBClassifier

from feature_extractor import extract_features, FEATURE_NAMES

warnings.filterwarnings("ignore")

HERE = os.path.dirname(os.path.abspath(__file__))
MODELS_DIR = os.path.join(HERE, "models")
RANDOM_STATE = 42


# --------------------------------------------------------------------------- #
# Dataset loading                                                             #
# --------------------------------------------------------------------------- #
def load_raw_dataframe():
    """
    Return a DataFrame with exactly two columns: 'url' (str) and 'label'
    (int, 0 = legitimate, 1 = phishing), picking the best dataset available.
    """
    # 1) Real PhiUSIIL dataset (best: large + balanced + raw URLs).
    phiusiil_candidates = glob.glob(
        os.path.join(HERE, "..", "..", "phiusiil+phishing+url+dataset", "*.csv")
    )
    if phiusiil_candidates:
        path = phiusiil_candidates[0]
        print(f"[data] Using PhiUSIIL dataset: {path}")
        df = pd.read_csv(path, usecols=["URL", "label"])
        # PhiUSIIL convention is INVERTED relative to our spec:
        #   raw label 1 = legitimate, raw label 0 = phishing.
        # Flip so that 0 = legitimate, 1 = phishing.
        df = df.rename(columns={"URL": "url"})
        df["label"] = 1 - df["label"].astype(int)
        return df[["url", "label"]]

    # 2) Local archive CSV (already has url + label in spec orientation).
    archive_path = os.path.join(HERE, "..", "..", "archive", "phishing_features.csv")
    if os.path.exists(archive_path):
        print(f"[data] Using archive dataset: {archive_path}")
        df = pd.read_csv(archive_path, usecols=["url", "label"])
        return df[["url", "label"]]

    # 3) Synthetic fallback.
    synth = os.path.join(HERE, "data", "phishing_urls.csv")
    print(f"[data] Using synthetic dataset: {synth}")
    df = pd.read_csv(synth)
    return df[["url", "label"]]


# --------------------------------------------------------------------------- #
# Main pipeline                                                               #
# --------------------------------------------------------------------------- #
def main():
    os.makedirs(MODELS_DIR, exist_ok=True)

    # ----- STEP 1: Load + inspect ----------------------------------------- #
    print("\n=== STEP 1: Load dataset & inspect ===")
    df = load_raw_dataframe()
    print("Shape:", df.shape)
    print("Missing values per column:\n", df.isnull().sum())
    print("Class distribution (0=legit, 1=phish):\n", df["label"].value_counts())

    # ----- STEP 2: Clean -------------------------------------------------- #
    print("\n=== STEP 2: Clean (dedupe + drop null urls/labels) ===")
    before = len(df)
    df = df.dropna(subset=["url", "label"])
    df = df.drop_duplicates(subset=["url"]).reset_index(drop=True)
    df["label"] = df["label"].astype(int)
    print(f"Removed {before - len(df)} duplicate/null rows -> {len(df)} remain")

    # Cap very large datasets for a fast, reproducible run while staying well
    # above the 5,000-row target. Stratified to preserve class balance.
    MAX_ROWS = 40000
    if len(df) > MAX_ROWS:
        df, _ = train_test_split(
            df, train_size=MAX_ROWS, random_state=RANDOM_STATE, stratify=df["label"]
        )
        df = df.reset_index(drop=True)
        print(f"Sampled down to {len(df)} rows for training speed")

    # ----- STEP 3: Feature extraction ------------------------------------- #
    print("\n=== STEP 3: Extract 15 features from URLs ===")
    feat_rows = [extract_features(u) for u in df["url"]]
    X = pd.DataFrame(feat_rows, columns=FEATURE_NAMES)
    y = df["label"].values

    # Fill any numeric nulls with the column median (defensive; extractor
    # never emits NaN, but the spec requires this step).
    X = X.fillna(X.median(numeric_only=True))
    print("Feature matrix shape:", X.shape)
    print("Feature names:", FEATURE_NAMES)

    # Train/test split (80/20, stratified).
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, random_state=RANDOM_STATE, stratify=y
    )
    print(f"Train: {X_train.shape}, Test: {X_test.shape}")

    # ----- STEP 4: Scale -------------------------------------------------- #
    print("\n=== STEP 4: StandardScaler ===")
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)  # transform only — no leakage

    # ----- STEP 5: Train 6 models ----------------------------------------- #
    print("\n=== STEP 5: Train 6 models ===")
    models = {
        "LogisticRegression": LogisticRegression(max_iter=1000, random_state=RANDOM_STATE),
        "DecisionTree": DecisionTreeClassifier(random_state=RANDOM_STATE),
        "RandomForest": RandomForestClassifier(n_estimators=200, random_state=RANDOM_STATE, n_jobs=-1),
        "XGBoost": XGBClassifier(
            n_estimators=200, max_depth=6, learning_rate=0.1,
            subsample=0.9, colsample_bytree=0.9,
            eval_metric="logloss", random_state=RANDOM_STATE, n_jobs=-1,
        ),
        "GaussianNB": GaussianNB(),
        "SVC": SVC(probability=True, random_state=RANDOM_STATE),
    }

    # ----- STEP 6: Evaluate each ------------------------------------------ #
    print("\n=== STEP 6: Evaluate all models ===")
    results = []
    for name, model in models.items():
        model.fit(X_train_scaled, y_train)
        pred = model.predict(X_test_scaled)
        acc = accuracy_score(y_test, pred)
        prec = precision_score(y_test, pred, zero_division=0)
        rec = recall_score(y_test, pred, zero_division=0)
        f1 = f1_score(y_test, pred, zero_division=0)
        cm = confusion_matrix(y_test, pred)
        results.append((name, acc, prec, rec, f1))
        print(f"\n{name}")
        print(f"  accuracy={acc:.4f} precision={prec:.4f} recall={rec:.4f} f1={f1:.4f}")
        print(f"  confusion matrix [ [TN FP] [FN TP] ]:\n{cm}")

    comparison = pd.DataFrame(
        results, columns=["Model", "Accuracy", "Precision", "Recall", "F1"]
    ).sort_values("F1", ascending=False).reset_index(drop=True)
    print("\n--- MODEL COMPARISON (sorted by F1) ---")
    print(comparison.to_string(index=False))

    best_name = comparison.iloc[0]["Model"]
    print(f"\nBest base model by F1: {best_name}")

    # ----- STEP 7: GridSearchCV on the best model ------------------------- #
    print(f"\n=== STEP 7: GridSearchCV on {best_name} (cv=5, scoring='f1') ===")
    param_grids = {
        "RandomForest": {
            "n_estimators": [100, 200, 300],
            "max_depth": [None, 10, 20],
            "min_samples_split": [2, 5],
        },
        "XGBoost": {
            "n_estimators": [100, 200, 300],
            "max_depth": [4, 6, 8],
            "learning_rate": [0.05, 0.1, 0.2],
        },
        "DecisionTree": {
            "max_depth": [None, 10, 20, 30],
            "min_samples_split": [2, 5, 10],
            "criterion": ["gini", "entropy"],
        },
        "LogisticRegression": {
            "C": [0.01, 0.1, 1, 10],
            "penalty": ["l2"],
            "solver": ["lbfgs"],
        },
        "SVC": {"C": [0.1, 1, 10], "kernel": ["rbf", "linear"], "gamma": ["scale"]},
        "GaussianNB": {"var_smoothing": [1e-9, 1e-8, 1e-7, 1e-6]},
    }

    base_estimators = {
        "RandomForest": RandomForestClassifier(random_state=RANDOM_STATE, n_jobs=-1),
        "XGBoost": XGBClassifier(eval_metric="logloss", random_state=RANDOM_STATE, n_jobs=-1),
        "DecisionTree": DecisionTreeClassifier(random_state=RANDOM_STATE),
        "LogisticRegression": LogisticRegression(max_iter=1000, random_state=RANDOM_STATE),
        "SVC": SVC(probability=True, random_state=RANDOM_STATE),
        "GaussianNB": GaussianNB(),
    }

    grid = GridSearchCV(
        estimator=base_estimators[best_name],
        param_grid=param_grids[best_name],
        cv=5,
        scoring="f1",
        n_jobs=-1,
        verbose=1,
    )
    grid.fit(X_train_scaled, y_train)
    print("Best params:", grid.best_params_)
    print("Best CV f1:", round(grid.best_score_, 4))
    best_model = grid.best_estimator_

    # ----- STEP 8: Final evaluation --------------------------------------- #
    print("\n=== STEP 8: Final evaluation on test set ===")
    final_pred = best_model.predict(X_test_scaled)
    final_f1 = f1_score(y_test, final_pred, zero_division=0)
    print(classification_report(y_test, final_pred, target_names=["legit(0)", "phish(1)"]))
    print("Confusion matrix:\n", confusion_matrix(y_test, final_pred))
    print(f"\nFINAL TEST F1 = {final_f1:.4f}  (target >= 0.85)")
    if final_f1 >= 0.85:
        print("TARGET MET [OK]")
    else:
        print("TARGET NOT MET [FAIL] - consider more data / features")

    # ----- STEP 9: Save artifacts ----------------------------------------- #
    # The Android app feeds RAW float[15] features straight into ONNX (no
    # on-device scaler). Tree ensembles (XGBoost/RF/DT) are scale-invariant,
    # so we deploy a FINAL model trained on RAW features. This guarantees the
    # ONNX graph's expected input == what Android produces. For linear/NB/SVC
    # winners we also refit on raw (our margin over 0.85 is huge either way).
    print("\n=== STEP 9: Refit winner on RAW features + save artifacts ===")
    from sklearn.base import clone

    deploy_model = clone(best_model)
    deploy_model.fit(X_train.values.astype(np.float32), y_train)

    # Sanity: raw-trained model still meets the target on the test set.
    raw_pred = deploy_model.predict(X_test.values.astype(np.float32))
    raw_f1 = f1_score(y_test, raw_pred, zero_division=0)
    print(f"Raw-feature deploy model test F1 = {raw_f1:.4f}")

    joblib.dump(deploy_model, os.path.join(MODELS_DIR, "optimized_model.pkl"))
    joblib.dump(scaler, os.path.join(MODELS_DIR, "scaler.pkl"))
    with open(os.path.join(MODELS_DIR, "feature_names.json"), "w", encoding="utf-8") as f:
        json.dump(FEATURE_NAMES, f, indent=2)
    print("Saved optimized_model.pkl (raw-feature), scaler.pkl, feature_names.json")

    # ----- STEP 10: Convert to ONNX (raw-feature input) ------------------- #
    print("\n=== STEP 10: Convert to ONNX ===")
    onnx_path = os.path.join(MODELS_DIR, "phishing_model.onnx")
    initial_name = "float_input"

    if isinstance(deploy_model, XGBClassifier):
        # XGBoost: convert with onnxmltools (consistent type system).
        from onnxmltools.convert import convert_xgboost
        from onnxmltools.convert.common.data_types import (
            FloatTensorType as MltFloatTensorType,
        )

        initial_type = [(initial_name, MltFloatTensorType([None, 15]))]
        onnx_model = convert_xgboost(deploy_model, initial_types=initial_type)
    else:
        # Everything else: native skl2onnx path.
        from skl2onnx import convert_sklearn
        from skl2onnx.common.data_types import FloatTensorType

        initial_type = [(initial_name, FloatTensorType([None, 15]))]
        onnx_model = convert_sklearn(
            deploy_model,
            initial_types=initial_type,
            options={id(deploy_model): {"zipmap": False}},
        )

    with open(onnx_path, "wb") as f:
        f.write(onnx_model.SerializeToString())
    print("Saved", onnx_path)

    # ----- STEP 11: Verify ONNX ------------------------------------------- #
    print("\n=== STEP 11: Verify ONNX vs sklearn on 5 raw samples ===")
    import onnxruntime as ort

    sess = ort.InferenceSession(onnx_path, providers=["CPUExecutionProvider"])
    input_name = sess.get_inputs()[0].name
    out_names = [o.name for o in sess.get_outputs()]
    print("ONNX input:", input_name, "outputs:", out_names)

    sample_raw = X_test.iloc[:5].values.astype(np.float32)
    sklearn_pred = deploy_model.predict(sample_raw)

    onnx_out = sess.run(None, {input_name: sample_raw})
    onnx_labels = np.asarray(onnx_out[0]).ravel()

    print(f"{'idx':<4}{'sklearn':<10}{'onnx':<10}{'match'}")
    all_match = True
    for i in range(5):
        match = int(sklearn_pred[i]) == int(onnx_labels[i])
        all_match &= match
        print(f"{i:<4}{int(sklearn_pred[i]):<10}{int(onnx_labels[i]):<10}{match}")
    print("\nALL 5 PREDICTIONS MATCH [OK]" if all_match else "\nMISMATCH DETECTED [FAIL]")

    print("\nDone. Artifacts in:", MODELS_DIR)


if __name__ == "__main__":
    main()
